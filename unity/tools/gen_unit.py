rows = []
for ln in FIELDS:
    parts = ln.split()
    name, typ, kind = parts[0], parts[1], parts[-1]
    dflt = " ".join(parts[2:-1])
    rows.append((name, typ, dflt, kind))

def cs_name(n):
    return "@" + n if n in ("super", "base", "out", "in", "lock", "params", "string", "object", "event") else n

out = []
w = out.append
w("// GENERATED by tools/gen_unit.py -- do not edit by hand; edit the FIELDS table there and rerun.")
w("// A unit of the sim: siege_sim.gd's unit Dictionary as a typed class. Field names are the dictionary keys (and the")
w("// online protocol's). Get/Set/Has/Erase by name serve the network's generic diffs and u.get(\"key\", default) reads.")
w("using System;")
w("using System.Collections.Generic;")
w("")
w("namespace Fatebound.Sim")
w("{")
w("    public sealed partial class Unit")
w("    {")
for name, typ, dflt, kind in rows:
    w(f"        public {typ} {cs_name(name)}{'' if dflt == 'null' else ' = ' + dflt};")
w("")
w("        /// <summary>The field names, in the order a fresh unit's dictionary would list them.</summary>")
w("        public static readonly string[] FieldNames = { " + ", ".join('"%s"' % r[0] for r in rows) + " };")
w("")
# Get
w("        /// <summary>u.get(key): the field boxed (int, double, bool, string, Vec2, Vec3, or the object); null when absent.</summary>")
w("        public object Get(string key)")
w("        {")
w("            switch (key)")
w("            {")
for name, typ, dflt, kind in rows:
    w(f'                case "{name}": return {cs_name(name)};')
w("                default: return extra != null && extra.TryGetValue(key, out var v) ? v : null;")
w("            }")
w("        }")
w("")
# Set
w("        /// <summary>u[key] = value (numbers converted to the field's type); unknown keys go to `extra`.</summary>")
w("        public void Set(string key, object v)")
w("        {")
w("            switch (key)")
w("            {")
for name, typ, dflt, kind in rows:
    n = cs_name(name)
    if typ == "int": conv = f"{n} = V.ToInt(v);"
    elif typ == "double": conv = f"{n} = V.ToDouble(v);"
    elif typ == "bool": conv = f"{n} = V.ToBool(v);"
    elif typ == "string": conv = f"{n} = v == null ? {dflt} : v.ToString();"
    elif typ == "Vec2": conv = f"{n} = V.ToVec2(v);"
    elif typ == "Vec3": conv = f"{n} = V.ToVec3(v);"
    else: conv = f"{n} = V.Convert<{typ}>(v);"
    w(f'                case "{name}": {conv} return;')
w("                default:")
w("                    if (extra == null) extra = new Dictionary<string, object>();")
w("                    extra[key] = v;")
w("                    return;")
w("            }")
w("        }")
w("")
# Erase
w("        /// <summary>u.erase(key): the field back to its default (absent).</summary>")
w("        public void Erase(string key)")
w("        {")
w("            switch (key)")
w("            {")
for name, typ, dflt, kind in rows:
    w(f'                case "{name}": {cs_name(name)} = {dflt if dflt != "null" else "null"}; return;')
w("                default: extra?.Remove(key); return;")
w("            }")
w("        }")
w("")
w("        public Dictionary<string, object> extra;")
w("    }")
w("}")
p = os.path.join(os.path.dirname(__file__), "..", "Assets", "Fatebound", "Sim", "Unit.g.cs")
